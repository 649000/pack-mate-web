-- Destination facts
-- Schema: packmate
-- Read-only reference data keyed by ISO 3166-1 alpha-2 country code: currency,
-- country calling code, electrical plug type(s), voltage, frequency and IANA
-- time zones. It is not user data, so there is a single public-read policy and
-- no write policies. Facts may be partial: some territories have no electricity
-- or currency data available from the sources, so those columns are nullable and
-- the application shows only the fields that are present.
--
-- The country_code check mirrors lib/countries.ts and the trips constraint in
-- 20260920000000_trip_destination.sql; lib/destination-facts.test.ts asserts the
-- two lists stay in sync.

create table packmate.destination_facts (
  country_code text primary key,
  currency_code text,
  calling_code text,
  plug_types text[] not null default '{}',
  voltage text,
  frequency text,
  timezones text[] not null default '{}',
  updated_at timestamptz not null default now(),
  constraint destination_facts_country_code_valid check (
    country_code in (
      'AD', 'AE', 'AF', 'AG', 'AI', 'AL', 'AM', 'AO', 'AQ', 'AR', 'AS', 'AT',
      'AU', 'AW', 'AX', 'AZ', 'BA', 'BB', 'BD', 'BE', 'BF', 'BG', 'BH', 'BI',
      'BJ', 'BL', 'BM', 'BN', 'BO', 'BQ', 'BR', 'BS', 'BT', 'BV', 'BW', 'BY',
      'BZ', 'CA', 'CC', 'CD', 'CF', 'CG', 'CH', 'CI', 'CK', 'CL', 'CM', 'CN',
      'CO', 'CR', 'CU', 'CV', 'CW', 'CX', 'CY', 'CZ', 'DE', 'DJ', 'DK', 'DM',
      'DO', 'DZ', 'EC', 'EE', 'EG', 'EH', 'ER', 'ES', 'ET', 'FI', 'FJ', 'FK',
      'FM', 'FO', 'FR', 'GA', 'GB', 'GD', 'GE', 'GF', 'GG', 'GH', 'GI', 'GL',
      'GM', 'GN', 'GP', 'GQ', 'GR', 'GS', 'GT', 'GU', 'GW', 'GY', 'HK', 'HM',
      'HN', 'HR', 'HT', 'HU', 'ID', 'IE', 'IL', 'IM', 'IN', 'IO', 'IQ', 'IR',
      'IS', 'IT', 'JE', 'JM', 'JO', 'JP', 'KE', 'KG', 'KH', 'KI', 'KM', 'KN',
      'KP', 'KR', 'KW', 'KY', 'KZ', 'LA', 'LB', 'LC', 'LI', 'LK', 'LR', 'LS',
      'LT', 'LU', 'LV', 'LY', 'MA', 'MC', 'MD', 'ME', 'MF', 'MG', 'MH', 'MK',
      'ML', 'MM', 'MN', 'MO', 'MP', 'MQ', 'MR', 'MS', 'MT', 'MU', 'MV', 'MW',
      'MX', 'MY', 'MZ', 'NA', 'NC', 'NE', 'NF', 'NG', 'NI', 'NL', 'NO', 'NP',
      'NR', 'NU', 'NZ', 'OM', 'PA', 'PE', 'PF', 'PG', 'PH', 'PK', 'PL', 'PM',
      'PN', 'PR', 'PS', 'PT', 'PW', 'PY', 'QA', 'RE', 'RO', 'RS', 'RU', 'RW',
      'SA', 'SB', 'SC', 'SD', 'SE', 'SG', 'SH', 'SI', 'SJ', 'SK', 'SL', 'SM',
      'SN', 'SO', 'SR', 'SS', 'ST', 'SV', 'SX', 'SY', 'SZ', 'TC', 'TD', 'TF',
      'TG', 'TH', 'TJ', 'TK', 'TL', 'TM', 'TN', 'TO', 'TR', 'TT', 'TV', 'TW',
      'TZ', 'UA', 'UG', 'UM', 'US', 'UY', 'UZ', 'VA', 'VC', 'VE', 'VG', 'VI',
      'VN', 'VU', 'WF', 'WS', 'YE', 'YT', 'ZA', 'ZM', 'ZW'
    )
  ),
  constraint destination_facts_currency_code_valid check (
    currency_code is null or currency_code ~ '^[A-Z]{3}$'
  ),
  constraint destination_facts_calling_code_valid check (
    calling_code is null or calling_code ~ '^\+[0-9]+$'
  ),
  constraint destination_facts_plug_types_valid check (
    plug_types <@ array['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J', 'K', 'L', 'M', 'N', 'O']
  )
);

alter table packmate.destination_facts enable row level security;

-- Read-only reference data: everyone can read, nobody can write.
create policy destination_facts_select on packmate.destination_facts
  for select to anon, authenticated
  using (true);

grant select on packmate.destination_facts to anon, authenticated;
